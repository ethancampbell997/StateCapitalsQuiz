
package edu.uga.cs.statecapitalsquiz;

import android.content.ContentValues;
import android.content.Context;
import android.database.Cursor;
import android.database.sqlite.SQLiteDatabase;
import android.util.Log;

import java.util.ArrayList;
import java.util.List;

public class QuizResultData {
    public static final String DEBUG_TAG = "QuizResultData";
    private SQLiteDatabase db;
    private DBHelper dbHelper;
    /**
     * returns all columns
     */
    private static final String[] allColumns = {
            DBHelper.QUIZ_RESULT_COLUMN_ID,
            DBHelper.QUIZ_RESULT_COLUMN_DATE,
            DBHelper.QUIZ_RESULT_COLUMN_RESULT
    };
    //constructor
    public QuizResultData(Context context) {
        dbHelper = DBHelper.getInstance(context);
    }
    //open db
    public void open() {
        db = dbHelper.getWritableDatabase();
        Log.d(DEBUG_TAG, "QuizResultData: db open");
    }

    //close db
    public void close() {
        if (dbHelper != null) {
            dbHelper.close();
            Log.d(DEBUG_TAG, "QuizResultData: db closed");
        }
    }
    public boolean isDBOpen() {
        return db.isOpen();
    }

    /**
     * get all previous quiz results
     * @return all results as a list
     */
    public List<QuizResult> retrieveAllQuizResults() {

        ArrayList<QuizResult> quizResults = new ArrayList<>();
        Cursor cursor = null;
        int columnIndex;

        try {
            // Execute the select query and get the Cursor to iterate over the retrieved rows
            cursor = db.query(DBHelper.TABLE_QUIZ_RESULT, allColumns,
                    null, null, null, null,
                    DBHelper.QUIZ_RESULT_COLUMN_DATE + " DESC");
            //collect all quiz results into a List
            if (cursor != null && cursor.getCount() > 0) {
                while (cursor.moveToNext()) {
                    if (cursor.getColumnCount() >= 3) {
                        //get all attribute values of this quiz result
                        columnIndex = cursor.getColumnIndex(DBHelper.QUIZ_RESULT_COLUMN_ID);
                        long id = cursor.getLong(columnIndex);
                        columnIndex = cursor.getColumnIndex(DBHelper.QUIZ_RESULT_COLUMN_DATE);
                        String date = cursor.getString(columnIndex);
                        columnIndex = cursor.getColumnIndex(DBHelper.QUIZ_RESULT_COLUMN_RESULT);
                        int result = cursor.getInt(columnIndex);
                        //create a new QuizResult object and set its id to the retrieved value
                        QuizResult quizResult = new QuizResult(date, result);
                        quizResult.setId(id);
                        //add it to the list
                        quizResults.add(quizResult);
                        Log.d(DEBUG_TAG, "Retrieved QuizResult: " + quizResult);
                    }
                }
            }
            if (cursor != null)
                Log.d(DEBUG_TAG, "Number of records from DB: " + cursor.getCount());
            else
                Log.d(DEBUG_TAG, "Number of records from DB: 0");
        }
        catch (Exception e) {
            Log.d(DEBUG_TAG, "Exception caught: " + e);
        }
        finally {
            //close cursor
            if (cursor != null) {
                cursor.close();
            }
        }
        //return a list of retrieved quiz results
        return quizResults;
    }
    //Store a new quiz result in the database.
    public QuizResult storeQuizResult(QuizResult quizResult) {
        // Prepare the values for all of the necessary columns in the table
        // and set their values to the variables of the QuizResult argument.
        // This is how we are providing persistence to a QuizResult object
        // by storing it as a new row in the database table.
        ContentValues values = new ContentValues();

        values.put(DBHelper.QUIZ_RESULT_COLUMN_DATE, quizResult.getDate());
        values.put(DBHelper.QUIZ_RESULT_COLUMN_RESULT, quizResult.getResult());

        // Insert the new row into the database table;
        // The id (primary key) is automatically generated by the database system
        // and returned from the insert method call.
        long id = db.insert(DBHelper.TABLE_QUIZ_RESULT, null, values);

        // store the id (the primary key) in the QuizResult instance, as it is now persistent
        quizResult.setId(id);

        Log.d(DEBUG_TAG, "Stored new quiz result with id: "
                + String.valueOf(quizResult.getId()));

        return quizResult;
    }
}
